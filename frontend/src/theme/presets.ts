export const DEFAULT_THEME_ID: ThemeId = 'qingflow'

export function getPreset(id: string | null | undefined): ThemePreset {
  return THEME_PRESETS.find((item) => item.id === id) || THEME_PRESETS[0]
}

export function applyThemeVars(preset: ThemePreset) {
  const root = document.documentElement
  root.setAttribute('data-theme', preset.id)
  root.style.colorScheme = preset.dark ? 'dark' : 'light'
  for (const [key, value] of Object.entries(preset.vars)) {
    root.style.setProperty(key, value)
  }
}

export function toAntdTheme(preset: ThemePreset): ThemeConfig {
  return {
    algorithm: preset.dark ? antdTheme.darkAlgorithm : antdTheme.defaultAlgorithm,
    token: {
      colorPrimary: preset.primary,
      colorInfo: preset.primary,
      colorBgLayout: preset.vars['--app-bg'],
      colorBgContainer: preset.vars['--app-surface'],
      colorBorder: preset.vars['--app-border'],
      colorBorderSecondary: preset.vars['--app-border'],
      colorText: preset.vars['--app-text'],
      colorTextSecondary: preset.vars['--app-text-secondary'],
      colorBgElevated: preset.vars['--app-surface'],
      borderRadius: preset.radius,
      fontFamily: FONT,
      controlHeight: 32,
      boxShadow: preset.vars['--app-shadow'] === 'none' ? 'none' : preset.vars['--app-shadow'],
      boxShadowSecondary: 'none',
    },
    components: {
      Layout: {
        siderBg: preset.vars['--app-sider-bg'],
        headerBg: preset.vars['--app-header-bg'],
        headerHeight: 64,
        headerPadding: '0 28px',
        bodyBg: preset.vars['--app-bg'],
      },
      Menu: {
        itemBg: 'transparent',
        itemSelectedBg: preset.vars['--app-menu-selected'],
        itemHoverBg: preset.vars['--app-menu-hover'],
        itemSelectedColor: preset.vars['--app-menu-selected-text'],
        itemColor: preset.siderDark ? 'rgba(255,255,255,0.72)' : preset.vars['--app-text-secondary'],
        groupTitleColor: preset.siderDark ? 'rgba(255,255,255,0.42)' : preset.vars['--app-text-secondary'],
        itemBorderRadius: Math.min(preset.radius, 8),
        itemMarginInline: 10,
        itemMarginBlock: 2,
        itemHeight: 40,
        iconSize: 16,
        activeBarBorderWidth: 0,
        activeBarWidth: 0,
        darkItemBg: 'transparent',
        darkItemSelectedBg: preset.vars['--app-menu-selected'],
        darkItemHoverBg: preset.vars['--app-menu-hover'],
        darkItemSelectedColor: preset.vars['--app-menu-selected-text'],
        darkItemColor: 'rgba(255,255,255,0.72)',
      },
      Button: {
        primaryShadow: 'none',
        defaultShadow: 'none',
        dangerShadow: 'none',
        primaryColor: preset.vars['--app-on-primary'],
      },
      Card: {
        headerFontSize: 16,
        headerFontSizeSM: 14,
        paddingLG: 20,
        colorBgContainer: preset.vars['--app-surface'],
      },
      Table: {
        headerBg: preset.vars['--app-surface-2'],
        headerColor: preset.vars['--app-text-secondary'],
        rowHoverBg: preset.vars['--app-surface-2'],
        headerSplitColor: 'transparent',
      },
      Tabs: {
        itemSelectedColor: preset.primary,
        inkBarColor: preset.primary,
        itemColor: preset.vars['--app-text-secondary'],
        itemHoverColor: preset.vars['--app-text'],
      },
      Input: {
        activeShadow: 'none',
      },
      Modal: {
        contentBg: preset.vars['--app-surface'],
        headerBg: preset.vars['--app-surface'],
        footerBg: preset.vars['--app-surface'],
        boxShadow: '0 12px 40px rgba(17, 17, 17, 0.08)',
      },
      Drawer: {
        colorBgElevated: preset.vars['--app-surface'],
      },
      Popover: {
        colorBgElevated: preset.vars['--app-surface'],
      },
      Dropdown: {
        colorBgElevated: preset.vars['--app-surface'],
      },
      Tag: {
        defaultBg: preset.vars['--app-surface-2'],
        defaultColor: preset.vars['--app-text'],
      },
    },
  }
}
